#!/usr/bin/env python3
"""TREY: quest table (TREY_PLAN.md 5.10, Phase 4 chunk 4f).

Reads docs/trey/quests.csv and writes (run by make, files only rewritten when they change):
    include/constants/trey_quests.h   QUEST_<id> = num, QUEST_COUNT (#defines only, scripts include it)
    src/data/trey/quests.h            gTreyQuests[QUEST_COUNT]: region, name, stage lines

See the CSV's header comment for the columns. The build fails on: a bad or repeated num/id, an unknown
region, a name over 20 characters, a quest without stages, or a stage line over 2 lines of 32 characters.
"""
import csv
import os
import re
import sys

CSV = "docs/trey/quests.csv"
OUT_CONST = "include/constants/trey_quests.h"
OUT_DATA = "src/data/trey/quests.h"
REGIONS = {"kanto": "TREY_DEX_KANTO", "orange": "TREY_DEX_ORANGE", "johto": "TREY_DEX_JOHTO",
           "hoenn": "TREY_DEX_HOENN", "sinnoh": "TREY_DEX_SINNOH", "kitakami": "TREY_DEX_KITAKAMI"}
MAX_QUESTS = 255   # 255 = QUEST_STAGE_DONE is a stage value, nums go 0..254
MAX_STAGES = 254   # stage values 1..254
NAME_MAX = 20
LINE_MAX = 32


def c_string(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\\\\n", "\\n")


def write_if_changed(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


def main():
    if not os.path.exists("Makefile"):
        print("quests_csv.py: run from the project's root folder.")
        return 1
    with open(CSV, encoding="utf-8") as f:
        rows = [r for r in f if r.strip() and not r.lstrip().startswith("#")]
    errors, quests, nums, ids = [], [], set(), set()
    for lineno, row in enumerate(csv.DictReader(rows), 2):
        where = f"{CSV}: quest '{row.get('id', '?')}'"
        try:
            num = int(row["num"])
        except (TypeError, ValueError):
            errors.append(f"{where}: num '{row['num']}' is not a number")
            continue
        qid = (row["id"] or "").strip()
        region = (row["region"] or "").strip().lower()
        name = (row["name"] or "").strip()
        stages = [s.strip() for s in (row["stages"] or "").split("|") if s.strip()]
        if not 0 <= num < MAX_QUESTS:
            errors.append(f"{where}: num {num} must be 0-{MAX_QUESTS - 1}")
        if num in nums:
            errors.append(f"{where}: num {num} is used twice")
        if not re.fullmatch(r"[A-Z0-9_]+", qid):
            errors.append(f"{where}: id must be UPPER_CASE")
        if qid in ids:
            errors.append(f"{where}: id is used twice")
        if region not in REGIONS:
            errors.append(f"{where}: unknown region '{region}' ({', '.join(REGIONS)})")
        if not name or len(name) > NAME_MAX:
            errors.append(f"{where}: name must be 1-{NAME_MAX} characters")
        if not stages or len(stages) > MAX_STAGES:
            errors.append(f"{where}: needs 1-{MAX_STAGES} stages")
        for i, line in enumerate(stages, 1):
            parts = line.split("\\n")
            if len(parts) > 2 or any(len(p) > LINE_MAX for p in parts):
                errors.append(f"{where}: stage {i} must be at most 2 lines of {LINE_MAX} characters")
        nums.add(num)
        ids.add(qid)
        quests.append((num, qid, region, name, stages))
    if errors:
        for e in errors:
            print("quests_csv.py: error: " + e)
        return 1

    quests.sort()
    count = (quests[-1][0] + 1) if quests else 1
    const = ["// Generated by tools/trey/quests_csv.py from docs/trey/quests.csv. Do not edit.",
             "#ifndef GUARD_CONSTANTS_TREY_QUESTS_H", "#define GUARD_CONSTANTS_TREY_QUESTS_H", "",
             "#define QUEST_STAGE_NONE  0   // not started", "#define QUEST_STAGE_DONE  255 // complete", ""]
    for num, qid, region, name, stages in quests:
        const.append(f"#define QUEST_{qid:<28} {num:>3} // {region}, {len(stages)} stage(s)")
    const += ["", f"#define QUEST_COUNT {count}", "", "#endif // GUARD_CONSTANTS_TREY_QUESTS_H", ""]

    data = ["// Generated by tools/trey/quests_csv.py from docs/trey/quests.csv. Do not edit.", ""]
    for num, qid, region, name, stages in quests:
        data.append(f"static const u8 *const sQuestStages_{qid}[] =")
        data.append("{")
        for line in stages:
            data.append(f'    COMPOUND_STRING("{c_string(line)}"),')
        data.append("};")
    data += ["", "const struct TreyQuest gTreyQuests[QUEST_COUNT] =", "{"]
    for num, qid, region, name, stages in quests:
        data.append(f"    [QUEST_{qid}] = {{ .region = {REGIONS[region]}, .numStages = {len(stages)}, "
                    f'.name = COMPOUND_STRING("{c_string(name)}"), .stages = sQuestStages_{qid} }},')
    data += ["};", ""]

    write_if_changed(OUT_CONST, "\n".join(const))
    write_if_changed(OUT_DATA, "\n".join(data))
    print(f"quests_csv.py: {len(quests)} quests -> {OUT_CONST}, {OUT_DATA}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
